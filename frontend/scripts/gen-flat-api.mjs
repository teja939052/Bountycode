#!/usr/bin/env node
/**
 * Generates src/services/api/flat.js — a flat alias layer that maps every
 * `api.<name>(...)` call used in src to its owning namespace method.
 * Run: node scripts/gen-flat-api.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const API_DIR = join(ROOT, "src", "services", "api");

function skipString(s, i) {
  const q = s[i];
  i++;
  while (i < s.length) {
    if (s[i] === "\\") { i += 2; continue; }
    if (s[i] === q) return i + 1;
    if (q === "`" && s[i] === "$" && s[i + 1] === "{") {
      let d = 0;
      i++;
      do { if (s[i] === "{") d++; else if (s[i] === "}") d--; i++; } while (d > 0 && i < s.length);
      continue;
    }
    i++;
  }
  return i;
}

function objectSlice(src, startBrace) {
  let depth = 0;
  let i = startBrace;
  while (i < src.length) {
    const c = src[i];
    if (c === '"' || c === "'" || c === "`") { i = skipString(src, i); continue; }
    if (c === "{") depth++;
    else if (c === "}") { depth--; if (depth === 0) return src.slice(startBrace + 1, i); }
    i++;
  }
  return src.slice(startBrace + 1);
}

const nsMethods = {};
const nsFile = {};
const STOP_KEYS = new Set(["method", "body", "if", "credentials", "requestWithRetry", "async", "function"]);
for (const f of readdirSync(API_DIR)) {
  if (!/\.(js|ts)$/.test(f) || f === "index.ts" || f === "flat.ts" || f === "flatOverrides.ts") continue;
  const src = readFileSync(join(API_DIR, f), "utf8");
  for (const m of src.matchAll(/export const (\w+Api)(?::\s*[^{]+)?\s*=\s*\{/g)) {
    const name = m[1];
    const obj = objectSlice(src, m.index + m[0].length - 1);
    for (const k of obj.matchAll(/^\s*(\w+)\s*[:\(]/gm)) {
      if (STOP_KEYS.has(k[1])) continue;
      (nsMethods[k[1]] = nsMethods[k[1]] || new Set()).add(name);
    }
    nsFile[name] = f;
  }
}

// hand-mapped overrides take priority over auto-generation
const OVERRIDES = new Set();
{
  const src = readFileSync(join(API_DIR, "flatOverrides.ts"), "utf8");
  for (const k of src.matchAll(/^\s{2}(\w+)\s*:/gm)) OVERRIDES.add(k[1]);
}

const srcDir = join(ROOT, "src");
function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]
  );
}

const namespaces = new Set();
const idx = readFileSync(join(API_DIR, "index.ts"), "utf8");
for (const m of idx.matchAll(/^\s*(\w+):\s*\w+Api,/gm)) namespaces.add(m[1]);

const TOP_LEVEL = new Set([
  "getMe", "register", "login", "logout", "updateProfile", "changePassword",
  "forgotPassword", "resetPassword", "onboardingStatus", "onboardingComplete",
  "cloudinaryImage", "cloudinaryVideo", "optimizeImage",
]);

const flat = new Map();
for (const file of walk(srcDir)) {
  if (!/\.(js|jsx|ts|tsx)$/.test(file)) continue;
  const src = readFileSync(file, "utf8");
  for (const m of src.matchAll(/\bapi\.([A-Za-z_$][\w$]*)/g)) {
    const name = m[1];
    if (namespaces.has(name) || TOP_LEVEL.has(name)) continue;
    const after = src.slice(m.index + m[0].length);
    if (!/^\s*(\(|\.|[=,)\]\s])/.test(after)) continue;
    flat.set(name, (flat.get(name) || 0) + 1);
  }
}

const imports = new Map();
const aliases = [];
const missing = [];
for (const [name, count] of flat) {
  if (OVERRIDES.has(name)) continue;
  const owners = [...(nsMethods[name] || [])];
  if (owners.length === 0) {
    missing.push(name);
    continue;
  }
  const owner = owners[0];
  imports.set(owner, nsFile[owner]);
  aliases.push(`  ${name}: (...args) => ${owner}.${name}.apply(${owner}, args),`);
}

const importLines = [...imports]
  .map(([api, file]) => `import { ${api} } from "./${file}";`)
  .join("\n");

const header = `// AUTO-GENERATED by scripts/gen-flat-api.mjs — flat aliases so both
// \`api.namespace.method()\` and legacy \`api.method()\` call styles work.
${importLines}

export const flatApi = {
${aliases.join("\n")}
};
`;

writeFileSync(join(API_DIR, "flat.ts"), header, "utf8");
console.log(`flat.ts written: ${aliases.length} aliases from ${imports.size} modules`);
if (missing.length) {
  console.log(`NO-OWNER flat methods (${missing.length}): ${missing.join(", ")}`);
}
