    "    def __init__(self, val=0, left=None, right=None):\n"
    "        self.val = val\n"
    "        self.left = left\n"
    "        self.right = right\n"
    "def build(arr):\n"
    "    if not arr or arr[0] is None:\n"
    "        return None\n"
    "    root = TreeNode(arr[0])\n"
    "    q = [root]\n"
    "    i = 1\n"
    "    while q and i < len(arr):\n"
    "        node = q.pop(0)\n"
    "        if i < len(arr) and arr[i] is not None:\n"
    "            node.left = TreeNode(arr[i])\n"
    "            q.append(node.left)\n"
    "        i += 1\n"
    "        if i < len(arr) and arr[i] is not None:\n"
    "            node.right = TreeNode(arr[i])\n"
    "            q.append(node.right)\n"
    "        i += 1\n"
    "    return root\n"
    "def to_level(root):\n"
    "    if not root:\n"
    "        return []\n"
    "    out = []\n"
    "    q = [root]\n"
    "    while q:\n"
    "        node = q.pop(0)\n"
    "        if node:\n"
    "            out.append(node.val)\n"
    "            q.append(node.left)\n"
    "            q.append(node.right)\n"
    "        else:\n"
    "            out.append(None)\n"
    "    while out and out[-1] is None:\n"
    "        out.pop()\n"
    "    return out"
