def search_companies(q: str) -> list:
    """Case-insensitive search across name, type, tags, and focus_areas."""
    if not q:
        return []
    query = q.strip().lower()
    results = []
    for company in COMPANIES:
        haystack = [
            str(company.get("name", "")),
            str(company.get("type", "")),
        ]
        haystack.extend([str(t) for t in company.get("tags", [])])
        haystack.extend([str(f) for f in company.get("focus_areas", [])])
        haystack.append(str(company.get("id", "")))
        if any(query in field.lower() for field in haystack):
            results.append(company)
    return results


